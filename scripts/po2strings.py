#!/usr/bin/env python3
"""po2strings.py — convert po/en.po into a macOS .strings file
(OpenStep plist, UTF-8) for the app bundle's en table. msgfmt is not
available on the Mac; this parser handles single-line + continued
msgid/msgstr and escapes. Skips fuzzy entries and empty msgstrs.

  scripts/po2strings.py po/en.po Harbor.app/Contents/Resources/en.strings
"""
import re, sys, pathlib

def unq(t):
    return re.sub(r'\\(.)',
                  lambda m: {'n': '\n', 't': '\t', '"': '"',
                             '\\': '\\'}.get(m.group(1), m.group(1)),
                  t[1:-1])

def parse(path):
    out, fuzzy = {}, False
    key = val = None
    field = None
    def flush():
        nonlocal key, val, fuzzy
        if key and val is not None and not fuzzy:
            out[key] = val
        key = val = None
    for line in pathlib.Path(path).read_text().splitlines():
        if line.startswith('#,') and 'fuzzy' in line:
            fuzzy = True
        elif line.startswith('msgid_plural'):
            field = 'plural'
        elif line.startswith('msgid '):
            flush(); fuzzy = False
            key = unq(line[6:].strip()); field = 'id'
        elif line.startswith('msgstr['):
            # 复数条目：%d 串取复数形（msgstr[1]），其余取 [0]
            n = int(line[line.index('[') + 1])
            v = unq(line[line.index(']') + 1:].strip())
            if val is None or ('%d' in (key or '') and n == 1):
                val = v
            field = 'str'
        elif line.startswith('msgstr '):
            val = unq(line[7:].strip()); field = 'str'
        elif line.startswith('"') and field == 'str':
            val += unq(line.strip())
        elif line.startswith('"') and field == 'id':
            key += unq(line.strip())
    flush()
    return out

def esc(s):
    return (s.replace('\\', '\\\\').replace('"', '\\"')
             .replace('\n', '\\n'))

def main():
    src, dst = sys.argv[1], sys.argv[2]
    table = parse(src)
    body = ''.join(f'"{esc(k)}" = "{esc(v)}";\n'
                   for k, v in sorted(table.items()))
    pathlib.Path(dst).write_text('/* generated by scripts/po2strings.py '
                                 'from po/en.po — do not edit */\n' + body)
    print(f'{dst}: {len(table)} entries')

if __name__ == '__main__':
    main()
